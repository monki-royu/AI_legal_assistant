# -*- coding: utf-8 -*-
"""
别名 / 条号归一化器 (Alias & Article-Number Normalizer)
=======================================================

【定位】
检索链路 Stage 1 (实体召回层) 的查询前处理层,
为 Neo4j 图谱查询和 FAISS 语义召回提供查询词/关键词归一化扩展。
解决两类"字面形式差异"导致的图谱召回失败(确定性问题, 不调 LLM, 查询期零新增延迟):

  失败模式① 条号写法差异
    图谱 Article 节点 name 存的是中文数字条号("第五百八十五条"),
    用户常输入阿拉伯数字("第585条")。
    L0 用 `n.name = $name` 精确匹配 → 两种写法互相找不到。
    → 本模块把"第585条"与"第五百八十五条"双向展开为同一组候选, 任一命中即可。

  失败模式② 法规简称 / 别名
    图谱 Law 节点 name 存的是官方全称("中华人民共和国民法总则"),
    用户输入简称("民总")。
    → 本模块用确定性简称词典把简称映射为官方全称候选。

【设计原则】
- 纯确定性函数 + 静态词典, 不调用任何 LLM / 远程服务;
- 只"增"不"减": 归一化是给候选集做"展开", 绝不删除原始候选,
  原始 query 永远保留(避免误伤);
- 幂等: 同一输入多次归一化结果一致。

【对外函数】
  - normalize_candidates(text: str) -> list[str]
      输入一段查询文本, 返回"展开后"的候选实体名列表(含原文本去重后的全部变体)。
      这是检索入口唯一需要调用的函数。

【维护说明】
简称词典 _SHORT_NAME_MAP 是按项目真实数据手维护的。新增常用简称时,
直接往字典里加一行即可(键=用户可能输入的简称, 值=图谱 Law 节点官方 name)。
"""
import re

# ======================================================================
# 中文数字 <-> 阿拉伯数字 转换 (仅覆盖条号需要的范围: 1~9999)
# ======================================================================
_CN_NUM = {
    "零": 0, "〇": 0, "一": 1, "二": 2, "两": 2, "三": 3, "四": 4,
    "五": 5, "六": 6, "七": 7, "八": 8, "九": 9,
    "十": 10, "百": 100, "千": 1000,
}


def _cn_to_int(s: str) -> int:
    """把中文数字串(如 "五百八十五")转成 int(585)。
    不支持"万"以上(条号用不到)。无法解析时返回 None。"""
    if not s:
        return None
    # 纯阿拉伯数字直接转
    if s.isdigit():
        return int(s)
    total, section, number = 0, 0, 0
    for ch in s:
        if ch in ("十", "百", "千"):
            unit = _CN_NUM[ch]
            # "十" 前无数字(如 "十二" 的 "十")按 1 处理
            number = number if number else 1
            section += number * unit
            number = 0
        elif ch in _CN_NUM:
            number = _CN_NUM[ch]
        else:
            return None  # 出现非数字字符, 放弃解析
    total = section + number
    return total if total else None


def _int_to_cn(n: int) -> str:
    """把 1~9999 的 int 转成中文数字串(如 585 -> "五百八十五")。
    超出范围返回空串(交给调用方忽略)。"""
    if n <= 0 or n >= 10000:
        return ""
    units = ["", "十", "百", "千"]
    digits = ["零", "一", "二", "三", "四", "五", "六", "七", "八", "九"]
    s = ""
    for i, ch in enumerate(reversed(str(n))):
        d = int(ch)
        if d:
            s = digits[d] + units[i] + s
        elif s and not s.startswith("零"):
            s = "零" + s
    # 规范化: "一十X" -> "十X" (中文习惯, 如 12 -> "十二" 而非 "一十二")
    s = re.sub(r"^一十", "十", s)
    # 去除中间多余的零 (如 105 -> "一百零五", 已正确; 1005 不在范围)
    return s


def _normalize_article_no(text: str) -> list:
    """把包含条号的文本展开为条号候选变体列表。
    例: "第585条"  -> ["第585条", "第五百八十五条"]
        "第五百八十五条" -> ["第五百八十五条", "第585条"]
    不匹配则返回空列表(非条号文本, 不动)。"""
    m = re.match(r"^第\s*([0-9零一二三四五六七八九十百千两]+)\s*条$", text.strip())
    if not m:
        return []
    raw = m.group(1)
    num = _cn_to_int(raw)
    if num is None:
        return []
    variants = {text.strip()}
    # 阿拉伯 -> 中文
    cn = _int_to_cn(num)
    if cn:
        variants.add(f"第{cn}条")
    # 中文 -> 阿拉伯 (当原串本就是阿拉伯时, cn 转换回不来, 这里显式补阿拉伯)
    if not raw.isdigit():
        variants.add(f"第{num}条")
    return list(variants)


