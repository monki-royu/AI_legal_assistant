def _expand_short_names(text: str) -> list:
    """把文本中出现的法规简称替换为官方全称候选。
    例: "民总第585条" -> ["民总第585条", "中华人民共和国民法总则第585条"]
    同时返回"纯简称命中"的官方全称(便于独立实体匹配)。
    返回去重后的变体列表。"""
    variants = {text}
    hits = []
    for short, full in _SHORT_NAME_MAP.items():
        if short in text:
            # 防重复前缀: 若文本已包含官方全称(如 "中华人民共和国民法总则" 已含自身),
            # 不应再对其中子串 "民法总则" 做替换, 否则产生 "中华人民共和国中华人民共和国民法总则"
            if full in text:
                continue
            expanded = text.replace(short, full)
            variants.add(expanded)
            hits.append(full)
    # 若文本本身就是某个简称(如用户只输入"民总"), 也补官方全称
    if text.strip() in _SHORT_NAME_MAP:
        variants.add(_SHORT_NAME_MAP[text.strip()])
    return list(variants), hits


# ======================================================================
# 对外主函数
# ======================================================================
def normalize_candidates(text: str) -> list:
    """查询前处理: 把一段文本展开为"图谱实体名候选"列表。

    展开规则(全部确定性, 不调 LLM):
      1. 原文本本身永远保留(去重后);
      2. 若文本是/含条号("第585条" / "第五百八十五条") → 补双向变体;
      3. 若文本是/含法规简称("民总") → 补官方全称变体。

    返回: list[str], 去重保序, 至少含原文本。

    Parameters
    ----------
    text : str
        待归一化的查询片段(可以是完整 query, 也可以是某个关键词候选)。

    Returns
    -------
    list[str]
        展开后的候选实体名列表(供 Neo4j `n.name = $name` 精确匹配逐一带入)。
    """
    if not text or not text.strip():
        return []

    out = {text.strip()}

    # 规则2: 条号双向归一(支持独立条号串, 或"法名+条号"整体)
    art_variants = _normalize_article_no(text)
    if art_variants:
        out.update(art_variants)
    else:
        # 文本里可能嵌着条号(如 "民总第585条"), 单独抽条号部分做归一
        m = re.search(r"第\s*([0-9零一二三四五六七八九十百千两]+)\s*条", text)
        if m:
            full_art = m.group(0)
            for v in _normalize_article_no(full_art):
                out.add(text.replace(full_art, v))

    # 规则3: 简称 -> 官方全称
    name_variants, _ = _expand_short_names(text)
    out.update(name_variants)

    return list(out)


