def crawl_single_law(law_info: dict, output_dir: str) -> tuple:
    """
    爬取单部法律(五级回退, 100% 有输出)
    返回 (文本, 来源)

    【作用】
        对单部法律执行五级数据源回退链：flk API → 人大网备用 URL → flk 详情页 DOM →
        LLM 生成 → 内置离线骨架 → 占位文本。每级判断文本长度是否达标(>1000或>500字符)，
        不达标则降级到下一级。最终100%写入文件(含头部元信息)，保证每部法律都有输出。
        已存在且>3000字符的文件直接跳过，支持断点续跑。

    【参数】
        law_info (dict): 法律信息字典，包含 name(法律名)、code(版本编号)、keywords(关键词)
        output_dir (str): 输出目录路径，txt 文件将写入该目录

    【返回值】
        tuple: (text, source) —— text 为法律文本，source 为数据来源描述字符串

    【可迁移性说明】
        该函数是五级回退链的调度核心，回退逻辑可迁移到任何多数据源采集场景。
        长度阈值(1000/500/3000)可根据实际数据质量调整。占位文本兜底保证极端情况下
        仍有输出，避免下游程序因缺文件崩溃。头部元信息格式(# 法律名/来源/时间)被
        下游 extract_law_data.py 的 _strip_header_lines 函数依赖，修改时需同步。
    """
    name = law_info["name"]  # 获取法律全称
    keywords = law_info.get("keywords", "")  # 获取关键词，默认空字符串
    out_path = os.path.join(output_dir, name + ".txt")  # 拼接输出 txt 文件完整路径

    # 已有文件且超过 3000 字符则视为有效完整版本, 直接跳过
    if os.path.exists(out_path) and os.path.getsize(out_path) > 3000:  # 文件存在且>3000字节(约1000汉字)
        with open(out_path, "r", encoding="utf-8") as f:  # 以 UTF-8 打开已有文件
            text = f.read()  # 读取全部内容
        print(f"[跳过] {name}: 已存在, {len(text)} 字符")  # 打印跳过提示
        return (text, "本地已存在")  # 返回已有文本和来源标记

    print(f"[抓取] {name} ...")  # 打印开始抓取提示

    text = ""  # 初始化文本为空
    src = ""  # 初始化来源为空

    # 回退 1: flk API (直抓 XHR 接口, 短超时避免卡住)
    text = try_flk_api(name)  # 调用 flk API 直抓
    if text and len(text) > 1000:  # 文本非空且超过1000字符
        src = "国家法律法规数据库API"  # 标记来源为 flk API
    else:  # 回退 1 失败，降级
        # 回退 2: 人大网备用 URL (短超时)
        text = try_npc_alt(name)  # 调用人大网备用 URL 抓取
        if text and len(text) > 1000:  # 文本非空且超过1000字符
            src = "全国人大网备用"  # 标记来源为人大网备用
        else:  # 回退 2 失败，降级
            # 回退 3: 通用 soup 抓取 DOM (flk 详情页, 超时 5s / 不重试)
            detail_url = f"https://flk.npc.gov.cn/detail2.html?{law_info.get('code', '')}"  # 拼接 flk 详情页 URL，传入法律 code
            soup = fetch_web_content(detail_url, timeout=5, max_retries=0)  # 抓取详情页 HTML，5秒超时，不重试
            if soup:  # 若抓取到 HTML
                text = extract_text_from_soup(  # 从 HTML 提取正文
                    soup,  # BeautifulSoup 对象
                    selectors=[".law-content", "#lawContent", "#content", ".content", "article"],  # 尝试多个正文 CSS 选择器
                )
            if text and len(text) > 1000:  # 正文非空且超过1000字符
                src = "flk详情DOM"  # 标记来源为 flk 详情页 DOM
            else:  # 回退 3 失败，降级
                # 回退 4: LLM 兜底生成 (API 依赖延迟导入, 失败静默)
                print("  [回退4] 使用LLM生成条文骨架")  # 打印 LLM 回退提示
                text = try_llm_generate(name, keywords)  # 调用 LLM 生成条文骨架
                if text and len(text) > 500:  # 文本非空且超过500字符（LLM 生成门槛较低）
                    src = "LLM生成骨架(兜底4)"  # 标记来源为 LLM 生成
                else:  # 回退 4 失败，降级
                    # 回退 5: 内置离线条文骨架 (100% 可用, 秒级生成)
                    print("  [回退5] 使用内置离线条文骨架")  # 打印离线骨架回退提示
                    text = BUILTIN_LAW_SKELETON.get(name, "")  # 从内置字典获取骨架文本
                    src = "内置离线骨架(极端兜底5)"  # 标记来源为内置离线骨架

    # 极端兜底: 如果连离线骨架都没命中, 写占位文本
    if not text or len(text) < 100:  # 若文本为空或不足100字符（离线骨架也没命中）
        text = (f"{name}\n核心关键词: {keywords}\n"  # 构造占位文本，含法律名和关键词
                "说明: 本文件为法律知识图谱占位文本, 建议联网后重新运行爬虫获取完整内容。")  # 占位说明
        src = "占位文本(极端兜底失败)"  # 标记来源为占位文本

    # 写文件 (100% 执行, 保证每部法律都有输出)
    with open(out_path, "w", encoding="utf-8") as f:  # 以 UTF-8 写模式打开输出文件
        header = f"# {name}\n# 来源: {src}\n# 生成时间: {time.strftime('%Y-%m-%d %H:%M:%S')}\n\n"  # 构造头部元信息：法律名、来源、生成时间
        f.write(header + text)  # 写入头部 + 正文
    print(f"  [OK] {src}, {len(text)} 字符 -> {os.path.basename(out_path)}")  # 打印成功信息
    return (text, src)  # 返回文本和来源


