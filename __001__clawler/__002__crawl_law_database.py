# ============ 数据源 1: flk.npc.gov.cn OFD 阅读器接口 ============
# 通过 reader/text API 直拿纯文本(SPA DOM 直抓无效, 参考经验: 抓真实 XHR 链路)
FLK_SEARCH_URL = "https://flk.npc.gov.cn/flk/search"  # flk 搜索接口 URL，按法律标题搜索获取结果列表
FLK_READER_TEXT_API = "https://flkofd.npc.gov.cn/reader/text"  # flk OFD 阅读器文本接口 URL，按文档 id 获取纯文本正文


def try_flk_api(law_name: str) -> str:
    """
    数据源1: flk 阅读器接口直抓 (通过 requests 调用真实 XHR)

    【作用】
        通过 requests 库调用国家法律法规数据库(flk.npc.gov.cn)的搜索接口查找法律文档，
        再调用 OFD 阅读器文本接口获取纯文本正文。该接口是 SPA 应用的真实 XHR 链路，
        直接抓 DOM 无效，必须抓 XHR 接口。任何环节失败均静默返回空字符串。

    【参数】
        law_name (str): 法律全称，如"中华人民共和国民法典"，作为搜索接口的 title 参数

    【返回值】
        str: 成功时返回法律纯文本正文；任何环节失败返回空字符串 ""

    【可迁移性说明】
        该函数封装了 flk.npc.gov.cn 的两步式抓取(搜索→取正文)，可迁移到任何需要
        从该数据库获取法律文本的场景。注意：接口返回结构可能随网站升级而变化，
        代码中对多种返回结构做了兼容(data.result.data / data.data / 任意 list 字段)。
        requests 为延迟导入，未安装时返回空字符串不影响程序运行。
    """
    try:  # 最外层 try 捕获 requests 导入失败
        import requests  # 延迟导入 requests，避免未安装时整个模块无法加载
        # 先搜索(简单 UA 模拟)
        # 构造请求头，模拟浏览器访问以绕过基本 UA 检测
        headers = {
            "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120 Safari/537.36",  # 模拟 Chrome 120 浏览器 UA
            "Referer": "https://flk.npc.gov.cn/",  # 设置 Referer 为 flk 首页，部分接口校验来源
        }
        # 搜索: flk/search 参数
        # 构造搜索参数：title 为法律名，page 为页码，limit 为每页条数
        params = {"title": law_name, "page": 1, "limit": 5}  # 搜索第1页，最多5条结果
        try:  # 捕获搜索请求的网络异常
            resp = requests.get(FLK_SEARCH_URL, params=params, headers=headers, timeout=12)  # 发送 GET 搜索请求，12秒超时
            if resp.status_code == 200:  # HTTP 200 表示请求成功
                try:  # 捕获 JSON 解析异常
                    data = resp.json()  # 将响应体解析为 JSON 字典
                    # 尝试提取首个结果的 id/link
                    # 兼容多种返回结构：优先取 result.data，其次 data，最后兜底
                    results = data.get("result", {}).get("data") or data.get("data") or []  # 尝试从常见路径提取结果列表
                    if not results and isinstance(data, dict):  # 若常规路径未取到结果且 data 是字典
                        for k, v in data.items():  # 遍历 data 所有字段
                            if isinstance(v, list):  # 找到第一个 list 类型字段
                                results = v  # 视其为结果列表
                                break  # 跳出遍历
                    if results:  # 若找到了搜索结果
                        first = results[0]  # 取第一条结果（最匹配的）
                        # 不同返回结构
                        # 尝试多种字段名获取文档 ID，兼容接口字段变更
                        ofd_id = first.get("id") or first.get("uuid") or first.get("fileId")  # 依次尝试 id / uuid / fileId 字段
                        if ofd_id:  # 若获取到了文档 ID
                            try:  # 捕获阅读器接口请求异常
                                r2 = requests.get(  # 调用阅读器文本接口获取纯文本
                                    FLK_READER_TEXT_API,  # 阅读器接口 URL
                                    params={"id": ofd_id},  # 传入文档 ID
                                    headers=headers,  # 复用请求头
                                    timeout=15,  # 15秒超时
                                )
                                if r2.status_code == 200 and r2.text.strip():  # 请求成功且文本非空
                                    return r2.text.strip()  # 返回去除首尾空白的纯文本
                            except Exception:  # 阅读器接口请求失败，静默忽略
                                pass  # 继续返回空字符串
                except Exception:  # JSON 解析失败，静默忽略
                    pass  # 继续返回空字符串
        except Exception:  # 搜索请求网络异常，静默忽略
            pass  # 继续返回空字符串
    except ImportError:  # requests 未安装，静默忽略
        pass  # 继续返回空字符串
    return ""  # 所有环节均未成功，返回空字符串


