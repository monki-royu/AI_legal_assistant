from typing import TypedDict, List, Dict, Optional  # 导入类型工具:TypedDict(带类型字典)/List(列表)/Dict(字典)/Optional(可空类型)


# ================================================================================
# 📜 定义 AgentState 类 —— 整张流水线的"状态蓝图"
# ================================================================================
# 【什么是 TypedDict?】 TypedDict 是 typing 模块提供的特殊类型,
#   它允许我们像"定义类"一样,声明"一个字典里有哪些键、每个键的值是什么类型"。
#   例如:class AgentState(TypedDict):  input: str 就表示
#   "这个字典里必须有一个名为 input 的键,它的值必须是字符串(str)"。
# 【为什么用它?】 这样既保持了字典的灵活性(运行时就是一个普通 dict,
#   可以直接作为 LangGraph 状态在节点间合并更新),又获得了静态类型检查的好处
#   (写代码时 IDE 能提示字段名,类型写错会报警)。
# 【total=False 参数的含义】 表示"所有字段都是可选的(optional)",
#   即创建状态实例时,不必提供所有键,缺哪个都行。
#   这一点非常关键:因为不同业务分支(如合同审核 vs 小红书发布)
#   只会写入自己路径上的相关字段;若 total=True(默认值),
#   则要求所有键必须存在,会导致大量空字段,违背灵活性原则。
# --------------------------------------------------------------------------------
class AgentState(TypedDict, total=False):
    # ============================================================================
    # 【第一类字段】==================== 输入(Input) ====================
    # 这一节的字段全部来自"用户这一侧":用户在前端界面输入了什么、上传了什么、
    # 选择了什么模式。它们是整条流水线的【起点数据】,在 START 之后被第一个节点读取。
    # 简单理解:这是"客户下单时填的订单信息",后面的所有处理都围绕它们展开。
    # ============================================================================

    # ----------------------------------------------------------------------------
    # 【字段】input —— 用户输入文本(用户原始输入)
    # ① 是什么(What): 存储用户在前端输入框里敲下的【原始文本】,
    #    可能是"帮我审核这份房屋租赁合同"这样的自然语言问题,
    #    也可能是用户直接粘贴进来的整份合同正文。
    # ② 为什么(Why):  它是整个流程的起点数据,没有它,系统不知道用户想干什么。
    # ③ 谁写入(Who writes): 前端调用入口(legal_response 系列函数)在发起请求时写入;
    # ④ 谁读取(Who reads):  intent_router_node(意图路由节点)读取它做意图识别,
    #    判断 task_type;后续各节点也把它当作上下文(context)使用;
    # ⑤ 示例值(Example): "请审核这份买卖合同的违约责任条款"
    # ----------------------------------------------------------------------------
    input: str                          # 用户输入文本：用户在前端输入的原始问题或合同全文，全流程起点

    # ----------------------------------------------------------------------------
    # 【字段】uploaded_doc_path —— 上传文档路径(文件在哪)
    # ① 是什么(What): 用户上传的合同/法规文档的【存储路径】,
    #    支持 txt / md / docx 等常见文本格式;
    # ② 为什么(Why):  用户在界面可能不是粘贴文本,而是上传了一个文件。
    #    系统需要知道"文件放在磁盘的哪个位置",才能去读取它;
    # ③ 谁写入(Who writes): 前端上传文件后,后端保存文件并回填路径;
    # ④ 谁读取(Who reads):  doc_extract_node(文档提取节点)读取该路径,
    #    用 LangChain 提供的各种文档加载器(Loader)按格式解析,
    #    把全文文本提取到 doc_text 字段;
    # ⑤ 示例值(Example): "C:/uploads/租赁合同.docx" 或对象存储 URL
    # ----------------------------------------------------------------------------
    uploaded_doc_path: str              # 上传文档路径(txt/md/docx)：用户上传的合同/法规文档的本地或远程路径

    # ----------------------------------------------------------------------------
    # 【字段】contract_type —— 合同类型(这份合同属于哪一类)
    # ① 是什么(What): 合同的业务分类,例如 买卖/租赁/借贷/建设工程/政府采购/劳动/服务/技术/其他;
    # ② 为什么(Why):  不同类型的合同,法律侧重点和风险点完全不同
    #    (比如租赁合同关注押金与维修责任,劳动合同时关注试用期与社保),
    #    所以需要先分类,再选用对应的审核规则;
    # ③ 谁写入(Who writes): contract_classify_node(合同分类节点)分析后写入;
    # ④ 谁读取(Who reads):  下游审核类节点(contract_ai_review_node 等)据此选取审核模板与法规依据;
    # ⑤ 示例值(Example): "租赁"
    # ----------------------------------------------------------------------------
    contract_type: str                  # 合同类型(买卖/租赁/借贷/建设工程/政府采购/劳动/服务/技术/其他)：影响后续审核规则的选取

    # ----------------------------------------------------------------------------
    # 【字段】review_strategy —— 审核策略(决定合同审核走哪条审核路径)
    # ① 是什么(What): 字符串枚举,决定合同审核使用哪一种审核策略;
    # ② 为什么(Why):  系统现在支持三级审核策略:
    #    - AI_AUTO:                完全由大模型(LLM)自动审核,用户不提供额外规则
    #                               → 走 N5a 合同审核AI(LLM) + N5b 合规审查
    #    - CUSTOM_RULES:           仅按用户自定义规则做确定性审核(正则/阈值/关键词)
    #                               → 走 N5-B 规则引擎,跳过 LLM 审查,快速出结果
    #    - CUSTOM_RULES_WITH_AI:   先走 N5-B 规则引擎,再由 N5a 做 AI 二次审核
    #                               → 规则兜底+AI 复核,双重保障
    # ③ 谁写入(Who writes): 由前端根据用户选择写入,或在意图路由阶段根据
    #    custom_rules 是否存在、user_config 中的策略设置写入;
    # ④ 谁读取(Who reads):  after_intent_router_router(条件路由,决定分流路径)、
    #    contract_ai_review_node(决定是否注入规则结果做 AI 二次审核)、
    #    rule_engine_node(决定扫描方式);
    # ⑤ 示例值(Example): "CUSTOM_RULES_WITH_AI"
    # ----------------------------------------------------------------------------
    review_strategy: str                # 审核策略：AI_AUTO | CUSTOM_RULES | CUSTOM_RULES_WITH_AI

    # ----------------------------------------------------------------------------
    # 【字段】strategy_weights —— 策略权重映射(每条规则/策略的权重分数)
    # ① 是什么(What): 字典,键是规则标识(如"rule_违约金上限"),值是权重(浮点数 0-100);
    # ② 为什么(Why):  当启用 CUSTOM_RULES / CUSTOM_RULES_WITH_AI 时,
    #    每条"用户自定义规则"或"规则引擎命中项"需要有独立的权重分,
    #    下游风险聚合节点据此做加权评分,而非一律等权。
    #    【设计思路来自 Word 图四】技术架构编排逻辑中,策略权重是用户规则审核
    #    与 AI 审核之间的调节旋钮——权重高的规则在风险聚合中被放大,
    #    权重低的规则仅作参考标记,不显著影响评分。
    # ③ 谁写入(Who writes): rule_engine_node 根据规则命中情况和预设权重写入;
    # ④ 谁读取(Who reads): risk_aggregate_node(风险聚合节点,加权评分);
    # ⑤ 示例值(Example): {"rule_违约金上限_50%": 80, "rule_管辖地_乙方所在地": 60}
    # ----------------------------------------------------------------------------
    strategy_weights: Dict[str, float]  # 策略权重映射：{"规则标识": 权重分(0-100)}，规则审核与AI审核之间的调节旋钮

    # ----------------------------------------------------------------------------
    # 【字段】rule_risk_items —— 规则引擎风险项(确定性规则扫描结果)
    # ① 是什么(What): 一个【列表】,元素是"用户自定义规则命中"的风险字典;
    # ② 为什么(Why):  当 review_strategy 为 CUSTOM_RULES 或 CUSTOM_RULES_WITH_AI 时,
    #    规则引擎(N5-B)用确定性代码(正则/阈值比对/关键词匹配)逐条扫描合同条款,
    #    命中的即为"确定性风险"——不需要 LLM 判断,规则本身即结论。
    #    这解决了"纯 LLM 审核可能漏检固定模式"的问题,也支持需要快速批量筛单的场景。
    #    规则命中的每个风险项还携带"规则权重"(strategy_weights 中的对应值),
    #    供下游风险聚合做加权评分时使用。
    # ③ 谁写入(Who writes): rule_engine_node(规则引擎节点,N5-B)输出;
    # ④ 谁读取(Who reads): risk_aggregate_node(风险聚合节点,汇入最终风险评分);
    # ⑤ 示例元素(Example): {"rule_id": "rule_违约金上限",
    #    "rule_name": "违约金不得超过合同总价的20%",
    #    "severity": "high",
    #    "description": "第八条约定的违约金比例30%超过用户自定义上限20%",
    #    "clause": "第八条",
    #    "segment_id": 8,
    #    "weight": 80.0,
    #    "hit_detail": "约定比例30% > 阈值20%"}
    # ----------------------------------------------------------------------------
    rule_risk_items: List[Dict]         # 规则引擎风险项：rule_engine_node 输出，确定性规则扫描结果，每条带权重分

    # ----------------------------------------------------------------------------
    # 【字段】custom_rules —— 自定义规则列表(用户自己定的审核标准)
    # ① 是什么(What): 一个【字符串列表】,每一项是一条用户自定义的审核规则;
    # ② 为什么(Why):  仅当 review_mode == CUSTOM_RULES 时才使用;
    #    企业法务常有自己的风控标准(如"付款比例不得超过合同总价的30%"),
    #    把这些规则喂给 LLM,让审核结果更贴合企业实际需求;
    # ③ 谁写入(Who writes): 前端收集用户输入/上传的规则后写入;
    # ④ 谁读取(Who reads):  contract_ai_review_node 读取并作为审核的附加依据;
    # ⑤ 示例值(Example): ["违约金不得超过合同总价的20%", "争议解决必须约定为仲裁"]
    # ----------------------------------------------------------------------------
    custom_rules: List[str]             # 自定义规则列表：仅在 CUSTOM_RULES 模式下使用，供合同AI审核参考

    # ============================================================================
    # 【第二类字段】==================== 意图路由(Intent Routing) ====================
    # 这一节的字段由【意图路由节点 intent_router_node】产出,
    # 作用是回答一个问题:"用户到底想干什么?"——然后据此把请求分流到不同的业务链路。
    # 简单理解:这是"总台接线员",先听清用户诉求,再转接到对应部门。
    # ============================================================================

    # ----------------------------------------------------------------------------
    # 【字段】task_type —— 任务类型(用户诉求的分类标签)
    # ① 是什么(What): 意图路由节点输出的【核心字段】,是整条流水线的"岔路口指示牌";
    # ② 为什么(Why):  下游条件路由(intent_router_router)完全依据它决定走向哪条业务链路;
    # ③ 谁写入(Who writes): intent_router_node 基于 input 做 LLM 意图识别后写入;
    # ④ 谁读取(Who reads): intent_router_router(条件路由函数)与后续各分支节点;
    # ⑤ 取值范围(Example): contract_review(合同审核)/compliance_review(合规审查)/
    #    legal_research(法律检索)/legal_qa(法律问答)/xiaohongshu(小红书)/
    #    legal_document_gen(法律文书生成)/case_search(案例检索)/other(其他,走通用兜底)
    # ----------------------------------------------------------------------------
    task_type: str                      # 任务类型：contract_review/compliance_review/legal_research/legal_qa/xiaohongshu/legal_document_gen/case_search/other

    # ============================================================================
    # 【第三类字段】==================== 意图锁定(Intent Lock, 优化后的新字段) ====================
    # 这是对系统的性能优化设计,核心思想:
    #   - 用户从【专用页面】进入(例如专门的法条检索页)→ 意图已经确定,不需要多源融合;
    #   - 用户从【首页/多智能体入口】进入 → 意图不确定,需要全量多源融合。
    # 简单理解:好比点外卖——用户已经走进"火锅店"了(intent_locked=True),
    # 就直接按火锅做;用户还在商场门口犹豫(intent_locked=False),
    # 就给他推荐全商场所有餐厅(RRF 多源融合)。
    # ============================================================================

    # ----------------------------------------------------------------------------
    # 【字段】intent_locked —— 意图是否锁定
    # ① 是什么(What): 布尔标志(Boolean),True 或 False;
    # ② 为什么(Why):  专用页面=True → 下游跳过 RRF 融合 + 减少数据源挂载(更快更省);
    #    首页/多智能体=False → 全量多源融合(更全面但更慢);
    # ③ 谁写入(Who writes): intent_router_node 根据入口来源/请求参数写入;
    # ④ 谁读取(Who reads): 检索链路节点(判断是否执行 RRF 融合、是否全量挂载数据源);
    # ⑤ 示例值(Example): True
    # ----------------------------------------------------------------------------
    intent_locked: bool                 # 意图锁定标志：True=专用页面意图已锁定；False=首页/多智能体需全量多源融合

    # ----------------------------------------------------------------------------
    # 【字段】mounted_sources —— 需要挂载的数据源列表
    # ① 是什么(What): 一个【列表】,里面的元素是数据源名称字符串;
    # ② 为什么(Why):  检索时不需要把所有数据源都查一遍——根据 task_type 只挂载相关的;
    #    例如查"法条"只需要 laws,查"案例"只需要 cases;
    # ③ 谁写入(Who writes): intent_router_node 根据 task_type 决定;
    # ④ 谁读取(Who reads): 检索基座层节点(retrieval_base_layer_node 等),
    #    按此列表决定检索哪些数据源;
    # ⑤ 取值范围(Example): ["laws", "cases", "industry", "interpretations"]
    #    或 ["*"] 表示全挂载
    # ----------------------------------------------------------------------------
    mounted_sources: list               # 需挂载的数据源列表：["laws","cases","industry","interpretations"] 或 ["*"]全挂载

    # ----------------------------------------------------------------------------
    # 【字段】sub_queries —— 检索意图分解后的子查询列表
    # ① 是什么(What): 一个【列表】,元素是子查询字符串;
    # ② 为什么(Why):  复杂法律问题需要拆成多个角度分别检索(如法律法规、司法案例),
    #    提升召回的全面性;
    # ③ 谁写入(Who writes): retrieval_intent_decompose_node 在 legal_qa 等场景写入;
    # ④ 谁读取(Who reads): 下游检索节点可按子查询逐个或合并检索;
    # ⑤ 示例值(Example): ["违约金约定的法律规定", "违约金过高的司法案例"]
    # ----------------------------------------------------------------------------
    sub_queries: list                  # 检索子查询列表：["子问1", "子问2", ...]

    # ----------------------------------------------------------------------------
    # 【字段】review_scope —— 检索拆解的法律面范围(task-aware 查询规划)
    # ① 是什么(What): 一个【列表】,元素是法律面标识字符串;
    # ② 为什么(Why):  检索"查询规划/分解"节点据此决定把原始查询拆成哪些角度:
    #    - ["commercial"]        → 只拆商业/合同风险面(合同审核用)
    #    - ["compliance"]        → 只拆合规/法条面(合规审查用)
    #    - ["legal_qa"]          → 把用户问题扩成子问(法律问答用,不拆法律面)
    #    - ["commercial","compliance"] → 双路并行拆解(合同审核整链)
    # ③ 谁写入(Who writes): 入口链路节点(如 extract_entity_from_user_input_node
    #    在 task_type==legal_qa 时写入 ["legal_qa"]),或 intent_router 按 task_type;
    # ④ 谁读取(Who reads): retrieval_intent_decompose_node 做查询拆解;
    # ⑤ 示例值(Example): ["legal_qa"]
    # ----------------------------------------------------------------------------
    review_scope: list                 # 检索拆解法律面：["legal_qa"] / ["commercial"] / ["compliance"] / 双路并行

    # ----------------------------------------------------------------------------
    # 【字段】skip_fusion —— 是否跳过 RRF 融合
    # ① 是什么(What): 布尔标志,True 表示"不做融合,直接返回检索结果";
    # ② 为什么(Why):  RRF(Reciprocal Rank Fusion,倒数排名融合)是把多个数据源的
    #    检索结果按排名加权合并的算法;意图已锁定时(intent_locked=True),
    #    只查单一数据源,没必要融合,跳过可省时;
    # ③ 谁写入(Who writes): intent_router_node 写入(锁定=True → 跳过);
    # ④ 谁读取(Who reads): retrieval_fusion_sort_node(融合排序节点),
    #    读到 True 时直接透传结果,不执行融合;
    # ⑤ 示例值(Example): True
    # ----------------------------------------------------------------------------
    skip_fusion: bool                   # 跳过RRF融合标志：锁定=True → 检索节点直接返回，不执行融合

    # ============================================================================
    # 【第四类字段】==================== 文档解析(Document Parsing) ====================
    # 这一节是"把用户上传的文档变成机器能处理的文本"的产物。
    # 简单理解:把一张张 PDF/Word 的"照片",翻译成电脑能逐行阅读的"纯文字"。
    # ============================================================================

    # ----------------------------------------------------------------------------
    # 【字段】doc_text —— 文档全文(纯文本)
    # ① 是什么(What): 一份【纯字符串】,保存了文档被解析后的全部文字内容;
    # ② 为什么(Why):  后续所有需要"读合同"的节点都基于它工作——
    #    full_text_segment_node 基于它做全文本统一切分,numeric_extract_node 基于它抽数值,
    #    审核/审查节点在 doc_segments 缺失时也会回退读它;
    # ③ 谁写入(Who writes): doc_extract_node(文档提取节点)解析 uploaded_doc_path 后写入;
    # ④ 谁读取(Who reads): full_text_segment_node / numeric_extract_node /
    #    contract_ai_review_node(回退) / compliance_review_node(回退) 等;
    # ⑤ 示例值(Example): "甲方:xxx公司……第一条 租赁物……"
    # ----------------------------------------------------------------------------
    doc_text: str                       # 文档全文：doc_extract_node 解析上传文档后得到的纯文本内容

    # ----------------------------------------------------------------------------
    # 【字段】doc_structured_json —— MinerU 结构化 JSON(多模态解析结果)
    # ① 是什么(What): 一个【字典(Dict)】,保存 MinerU(一种多模态文档解析模型)
    #    输出的结构化结果;
    # ② 为什么(Why):  纯文本会丢失版式信息(表格、图片位置、文字坐标)。
    #    结构化 JSON 保留了层级结构:pages(页)→ blocks(块)→ {type, content, bbox},
    #    其中 type 区分文字/表格/图片,bbox 是坐标框(用于在 PDF 上定位高亮);
    # ③ 谁写入(Who writes): doc_extract_mineru_node(MinerU 解析节点)写入;
    #    当 MinerU 不可用时,自动降级为"纯文本包装的 fallback JSON"(兜底结构);
    # ④ 谁读取(Who reads): 需要版式/表格信息的节点(如条款切分、风险定位);
    # ⑤ 结构示例(Example):
    #    {"metadata": {...}, "pages": [{"page_idx": 0,
    #      "blocks": [{"type": "text", "content": "...", "bbox": [x1,y1,x2,y2]}]}]}
    # ----------------------------------------------------------------------------
    doc_structured_json: Dict           # MinerU结构化JSON：{metadata, pages:[{page_idx, blocks:[{type,content,bbox}]}]}，多模态解析结果

    # ----------------------------------------------------------------------------
    # 【字段】doc_segments —— 全文本统一切分单元(替代旧的"仅第X条"切分)
    # ① 是什么(What): 一个【列表】,每个元素是一个【字典】,代表文档中的一个"审查单元";
    #    单元类型有三种: preamble(前言/开头非条款文字)、clause(第X条结构化条款)、
    #    paragraph(非结构化段落聚合而成的单元);
    # ② 为什么(Why):  旧的 clause_split_node 用正则只切"第X条",导致两个硬伤——
    #    (a) 正则 split 后从 index=1 开始遍历,把 index=0 的【前言直接丢弃】
    #        (而"本合同由甲方…甲方有采购需求"这类前言常含数据授权/主体资格风险);
    #    (b) 没有"第X条"的文档(如会议纪要、往来函件、OCR 出来没换行的一整坨文本)
    #        会退化成 1 个巨型单元或整体丢失,审查粒度归零。
    #    全文本统一切分保证【原文零丢失 + 每段都有编号】,审查才能真正做到可追溯。
    # ③ 谁写入(Who writes): full_text_segment_node(全文本统一切分节点)基于 doc_text 输出;
    # ④ 谁读取(Who reads): context_pack_node(算检索覆盖率)、contract_ai_review_node(N5a)、
    #    compliance_review_node(N5b)——两者都按单元编号定位风险并回填 segment_id;
    # ⑤ 元素结构(Example):
    #    {"id": 1, "type": "preamble", "title": "前言", "text": "本合同由……",
    #     "char_start": 0, "char_end": 42}
    #    {"id": 2, "type": "clause", "title": "第一条", "text": "第一条 租赁物……",
    #     "char_start": 42, "char_end": 210}
    # ----------------------------------------------------------------------------
    doc_segments: List[Dict]            # 全文本统一切分单元：[{id, type(preamble/clause/paragraph), title, text, char_start, char_end}]，原文零丢失且带编号可追溯

    # ----------------------------------------------------------------------------
    # 【字段】doc_clauses —— 切分后的条款列表(向后兼容投影)
    # ① 是什么(What): 一个【列表】,每个元素是一个【字典】,代表合同中的一条条款;
    # ② 为什么(Why):  合同审核需要"逐条"进行,而不是整篇混在一起;
    #    切分后便于按条款定位风险点,并在最终报告中逐条给出结论;
    #    【注意】本字段现已降级为 doc_segments 的【向后兼容投影】——
    #    full_text_segment_node 在写 doc_segments 的同时,把其中 type=="clause" 的单元
    #    投影成 doc_clauses(若一条 clause 都没有,则投影全部单元),
    #    使历史上读 doc_clauses 的节点(risk_aggregate/final_delivery 等)不必改动。
    #    新代码请优先读 doc_segments。
    # ③ 谁写入(Who writes): full_text_segment_node(全文本统一切分节点,投影产出);
    #    (历史实现为 clause_split_node,已被 full_text_segment_node 替代)
    # ④ 谁读取(Who reads): risk_aggregate_node、final_delivery_node(按条款生成报告)等历史消费方;
    # ⑤ 元素结构(Example):
    #    {"id": 1, "title": "第一条 租赁物", "text": "……", "bbox": [x1,y1,x2,y2](可选,PDF定位用)}
    # ----------------------------------------------------------------------------
    doc_clauses: List[Dict]             # 切分后的条款(doc_segments 中 clause 单元的向后兼容投影)：[{id, title, text, bbox?}]

    # ----------------------------------------------------------------------------
    # 【字段】review_context_bundle —— 检索上下文包(喂给下游审核/审查智能体的结构化字段)
    # ① 是什么(What): 一个【字典】,把"检索这一步到底做了什么、得到了什么、漏了什么"
    #    完整打包成一个结构化对象;
    # ② 为什么(Why):  架构上把检索前置到审核之前,本意是"审核时手里有法条依据"。
    #    但旧实现里 retrieval_output_node 算出的 citations / research_context
    #    【没有任何审核节点读取】——检索算完就被丢掉,"检索提前"只是流程图上的接线,
    #    对审核结论毫无影响。本字段就是把这条数据通路真正接上。
    #    另一个关键设计是【把"没检索到的部分"也传下去】:
    #    只喂召回结果会让 LLM 误以为那就是全部依据,从而对无依据的条款编造法条;
    #    显式告知"这些单元没有检索覆盖",LLM 才能选择"标注依据不足"而非幻觉引用。
    # ③ 谁写入(Who writes): context_pack_node(检索上下文打包节点),
    #    位于 retrieval_output_node 之后、审核/审查节点之前;
    # ④ 谁读取(Who reads): contract_ai_review_node(N5a)、compliance_review_node(N5b);
    # ⑤ 结构示例(Example):
    #    {"retrieval_query": "违约金比例是否过高……",        # 检索原始查询文本
    #     "retrieval_keywords": ["违约金", "民法典"],          # 检索关键词
    #     "citations": [...],                                  # 完整召回条目(原样透传)
    #     "citations_brief": [{"title","article_no","content"}],# 精简版,直接注入 prompt
    #     "research_context": "【民法典第五百八十五条】……",     # 连续上下文文本
    #     "quality_score": 82.5,                               # 检索质量分
    #     "segment_total": 12,                                 # 切分单元总数
    #     "retrieved_segment_ids": [2, 5, 7],                   # 被检索覆盖的单元编号
    #     "unretrieved_segments": [{"id":1,"title":"前言"}],     # 未被覆盖的单元(无法条依据)
    #     "coverage_ratio": 0.25}                              # 覆盖率
    # ----------------------------------------------------------------------------
    review_context_bundle: Dict         # 检索上下文包：{retrieval_query, retrieval_keywords, citations, citations_brief, research_context, quality_score, segment_total, retrieved_segment_ids, unretrieved_segments, coverage_ratio}

    # ============================================================================
    # 【第五类字段】==================== 数值抽取(Numeric Extraction) ====================
    # 合同里有大量关键数字:单价、数量、总价、税率、违约金、保证金、付款比例……
    # 这一节把这些数字"挖"出来集中存放,供后续做数学校验。
    # ============================================================================

    # ----------------------------------------------------------------------------
    # 【字段】extracted_numerics —— 抽取的数值实体字典
    # ① 是什么(What): 一个【字典】,以"键值对"形式保存从合同文本中抽出的关键数值;
    # ② 为什么(Why):  法律风险常常藏在数字矛盾里(如"总价=单价×数量"对不上),
    #    先把数字结构化,才能做自动化校验;
    # ③ 谁写入(Who writes): numeric_extract_node(数值抽取节点),
    #    通过正则(Regex)或 LLM 从合同文本中抽取;
    # ④ 谁读取(Who reads): numeric_validate_node(数值校验节点),
    #    用它校验逻辑一致性(如单价×数量是否等于总价、比例是否超标);
    # ⑤ 示例值(Example): {"单价": 5000, "数量": 100, "总价": 500000,
    #    "税率": 0.13, "违约金": 100000, "保证金": 50000, "付款比例": 0.3}
    # ----------------------------------------------------------------------------
    extracted_numerics: Dict            # 抽取的数值实体：{单价/数量/总价/税率/违约金/保证金/付款比例...}，供数值校验使用

    # ============================================================================
    # 【第六类字段】==================== 风险项(三路并行检测) ====================
    # 这一节是系统的"体检报告"核心:三条独立的风险检测路径同时/依次工作,
    # 每条路径产出一份风险清单。理论上三路可并行执行(项目中以串行模拟)。
    # 每个风险项字典通常包含:条款id、标题、风险描述、严重程度、建议修改等字段,
    # 具体结构由各检测节点自行定义。
    # ============================================================================

    # ----------------------------------------------------------------------------
    # 【字段】contract_risk_items —— 合同审核风险项
    # ① 是什么(What): 一个【列表】,元素是"合同本身风险"的字典;
    # ② 为什么(Why):  主要检测条款措辞、权责划分、违约金设置等合同自身的问题
    #    (例如"违约金约定过高,可能被法院调减");
    # ③ 谁写入(Who writes): contract_ai_review_node(合同AI审核节点)输出;
    # ④ 谁读取(Who reads): risk_aggregate_node(风险聚合节点)汇入最终风险清单;
    # ⑤ 示例元素(Example): {"clause_id": 5, "title": "违约金条款",
    #    "description": "违约金为合同总价50%,过高", "severity": "high", "suggestion": "建议调整为不超过30%"}
    # ----------------------------------------------------------------------------
    contract_risk_items: List[Dict]     # 合同审核风险项：contract_ai_review_node 输出，检测条款措辞/权责/违约金等合同本身风险

    # ----------------------------------------------------------------------------
    # 【字段】compliance_risk_items —— 合规审查风险项
    # ① 是什么(What): 一个【列表】,元素是"违反法律法规"的合规风险字典;
    # ② 为什么(Why):  合同内容不仅要合理,还要合法——比如违反《民法典》强制性规定
    #    的条款可能直接无效;
    # ③ 谁写入(Who writes): compliance_review_node(合规审查节点)输出;
    # ④ 谁读取(Who reads): risk_aggregate_node(风险聚合节点)汇入最终风险清单;
    # ⑤ 示例元素(Example): {"clause_id": 2, "description": "约定免除人身损害赔偿
    #    责任的条款违反《民法典》第506条", "severity": "high", "law_ref": "民法典第506条"}
    # ----------------------------------------------------------------------------
    compliance_risk_items: List[Dict]   # 合规审查风险项：compliance_review_node 输出，检测是否符合相关法律法规(如《民法典》)

    # ----------------------------------------------------------------------------
    # 【字段】numeric_risk_items —— 数值校验风险项
    # ① 是什么(What): 一个【列表】,元素是"数字有问题"的风险字典;
    # ② 为什么(Why):  检测数值一致性(单价×数量=总价?)、比例合理性(付款比例之和≤100%?)、
    #    是否超标(违约金超过法定上限?)等;
    # ③ 谁写入(Who writes): numeric_validate_node(数值校验节点)输出;
    # ④ 谁读取(Who reads): risk_aggregate_node(风险聚合节点)汇入最终风险清单;
    # ⑤ 示例元素(Example): {"field": "总价", "expected": 500000, "actual": 450000,
    #    "description": "总价与单价×数量不一致", "severity": "medium"}
    # ----------------------------------------------------------------------------
    numeric_risk_items: List[Dict]      # 数值校验风险项：numeric_validate_node 输出，检测数值一致性/比例合理性/是否超标

    # ============================================================================
    # 【第七类字段】==================== 检索(Retrieval) ====================
    # 这一节服务于"法律检索链路"。检索链路被拆成了 5 个节点,中间需要传递
    # 多个临时字段(检索词、关键词、各层检索结果等),因此新增了下面的中间字段。
    # 简单理解:这一节记录"查资料的过程和查到的东西"。
    # ============================================================================

    # ----------------------------------------------------------------------------
    # 【字段】retrieval_query —— 意图分解后的查询字符串
    # ① 是什么(What): 字符串,是用户原始问题被【意图分解】后得到的、适合检索的查询句;
    # ② 为什么(Why):  用户口语化的问题("拖欠工资怎么办")需要改写成检索友好的查询
    #    ("劳动报酬 拖欠 仲裁 法律依据"),召回效果才好;
    # ③ 谁写入(Who writes): retrieval_intent_decompose_node(检索意图分解节点)写入;
    # ④ 谁读取(Who reads): retrieval_base_layer_node / retrieval_enhance_query_node;
    # ⑤ 示例值(Example): "劳动合同 解除 经济补偿 计算标准"
    # ----------------------------------------------------------------------------
    retrieval_query: str                # 意图分解后的查询字符串：供检索基座层/增强层使用

    # ----------------------------------------------------------------------------
    # 【字段】retrieval_keywords —— 意图分解后的关键词列表
    # ① 是什么(What): 字符串列表,是从用户问题中拆出的核心关键词;
    # ② 为什么(Why):  关键词适合做精确匹配/向量检索的补充召回;
    # ③ 谁写入(Who writes): retrieval_intent_decompose_node 写入;
    # ④ 谁读取(Who reads): retrieval_base_layer_node(基础层检索)等;
    # ⑤ 示例值(Example): ["劳动合同", "解除", "经济补偿"]
    # ----------------------------------------------------------------------------
    retrieval_keywords: List[str]       # 意图分解后的关键词列表：供检索基座层做关键词召回

    # ----------------------------------------------------------------------------
    # 【字段】base_citations —— 基础层检索结果
    # ① 是什么(What): 列表,元素是基础层检索命中的"引用条目"字典;
    # ② 为什么(Why):  基础层 = FAISS 向量检索 + 本地法规库精确检索,是第一轮召回结果;
    # ③ 谁写入(Who writes): retrieval_base_layer_node(基础层检索节点)写入;
    # ④ 谁读取(Who reads): retrieval_fusion_sort_node(融合排序节点)与最终输出节点;
    # ⑤ 示例元素(Example): {"title": "民法典", "article_no": "第五百八十五条",
    #    "content": "……", "source": "民法典", "score": 0.92}
    # ----------------------------------------------------------------------------
    base_citations: List[Dict]          # 基础层检索结果：FAISS向量检索 + 本地法规检索的召回条目

    # ----------------------------------------------------------------------------
    # 【字段】enhance_citations —— 增强层检索结果
    # ① 是什么(What): 列表,元素是增强层检索命中的引用条目字典;
    # ② 为什么(Why):  基础层召回不够时,由 LLM 进行【补充检索】(enhance),
    #    例如用 LLM 生成更宽的检索词、补查司法解释等;
    # ③ 谁写入(Who writes): retrieval_enhance_query_node(增强检索节点)写入;
    # ④ 谁读取(Who reads): retrieval_fusion_sort_node(融合排序节点);
    # ⑤ 示例元素(Example): 同 base_citations 结构
    # ----------------------------------------------------------------------------
    enhance_citations: List[Dict]       # 增强层检索结果：LLM补充检索得到的引用条目

    # ----------------------------------------------------------------------------
    # 【字段】research_context —— 检索结果上下文
    # ① 是什么(What): 字符串,把检索到的相关法规、案例文本拼接成的上下文;
    # ② 为什么(Why):  它是 final 报告生成时 LLM 的"参考资料"——
    #    没有它,LLM 只能凭记忆回答,容易产生幻觉(Hallucination);
    # ③ 谁写入(Who writes): legal_research_node(法律检索节点)输出(或检索输出节点);
    # ④ 谁读取(Who reads): 最终报告/答案生成节点;
    # ⑤ 示例值(Example): "【民法典第五百八十五条】当事人可以约定一方违约时……\n【案例】(2021)京民终123号……"
    # ----------------------------------------------------------------------------
    research_context: str               # 检索结果上下文：通过 FAISS/Neo4j 召回的相关法规、案例文本，作为最终报告依据

    # ----------------------------------------------------------------------------
    # 【字段】citations —— 引用列表(带结构化信息的法条引用)
    # ① 是什么(What): 列表,每个元素描述一条"具体法规条款";
    # ② 为什么(Why):  报告里要标注引用来源(法条号),提高可信度与可核验性;
    #    与 research_context 的区别:这里是【结构化】的条目,便于前端渲染角标;
    # ③ 谁写入(Who writes): 检索链路各层节点汇总后写入;
    # ④ 谁读取(Who reads): final_delivery_node(报告生成)与前端展示;
    # ⑤ 示例元素(Example): {"title": "民法典", "article_no": "第五百八十五条",
    #    "content": "……", "source": "民法典"}
    # ----------------------------------------------------------------------------
    citations: List[Dict]               # 引用列表：[{title, article_no, content, source}]，报告中标注引用来源提高可信度

    # ----------------------------------------------------------------------------
    # 【字段】quality_score —— 检索质量分
    # ① 是什么(What): 浮点数(0~100),反映本次检索结果的相关性高低;
    # ② 为什么(Why):  分数可用于:
    #    - 在风险聚合时调整评分权重(引用质量高的结论权重更高);
    #    - 质量过低时触发【降级策略】(走 LLM 伪检索兜底);
    # ③ 谁写入(Who writes): 检索质量门禁相关节点计算后写入;
    # ④ 谁读取(Who reads): 质量门禁路由函数、风险聚合节点;
    # ⑤ 示例值(Example): 85.5
    # ----------------------------------------------------------------------------
    quality_score: float                # 检索质量分(0-100)：反映检索结果相关性，可用于调权或触发降级策略

    # ----------------------------------------------------------------------------
    # 【字段】quality_retry_count —— 质量门禁重试次数
    # ① 是什么(What): 整数,记录当前是第几轮重试(0=首次, 1=第1轮重试, 2=第2轮, 3=第3轮);
    # ② 为什么(Why):  质量分不达标时允许重新检索,但不能无限重试——最多 3 轮;
    # ③ 谁写入(Who writes): 质量门禁节点每次重试后 +1;
    # ④ 谁读取(Who reads): 质量门禁路由函数,判断是否达到上限;
    # ⑤ 示例值(Example): 2
    # ----------------------------------------------------------------------------
    quality_retry_count: int            # 质量门禁重试计数(0~3)：0=首次，1~3为第1~3轮重试

    # ----------------------------------------------------------------------------
    # 【字段】quality_gate_passed —— 质量门是否通过
    # ① 是什么(What): 布尔标志, 检索质量是否达标;
    # ② 为什么(Why):  quality_gate_retry 节点根据该字段决定放行或回边重试;
    # ③ 谁写入(Who writes): retrieval_output_node / quality_gate_retry_node;
    # ④ 谁读取(Who reads): 质量门路由函数 _quality_gate_router;
    # ⑤ 示例值(Example): True / False
    # ----------------------------------------------------------------------------
    quality_gate_passed: bool           # 质量门是否通过：True=放行, False=回边重试

    # ----------------------------------------------------------------------------
    # 【字段】quality_max_retries —— 质量门最大重试次数
    # ① 是什么(What): 整数, 质量门重试上限(默认 3);
    # ② 为什么(Why):  防止质量门无限回边死循环;
    # ③ 谁写入(Who writes): retrieval_output_node;
    # ④ 谁读取(Who reads): 质量门路由函数;
    # ⑤ 示例值(Example): 3
    # ----------------------------------------------------------------------------
    quality_max_retries: int            # 质量门最大重试次数(默认3)：超限强制放行

    # ----------------------------------------------------------------------------
    # 【字段】fusion_mode —— 检索融合模式
    # ① 是什么(What): 字符串, 检索结果的融合方式;
    # ② 为什么(Why):  单源直查(case_search)跳过跨源融合省计算,
