# 📜 代码文字逻辑解析
# 本文件是 AI 法律助理(LangGraph 多智能体系统)中的"条款切分节点", 对应业务流程的 N4 环节。
# 其核心职责是: 将合同全文(state["doc_text"])按"第X条"标记切分为结构化的条款列表,
# 写入 state["doc_clauses"], 供后续 AI 审核、报告生成等节点按条款定位风险点。
# 节点采用 "正则规则切分 + 段落回退" 双层策略:
# (1) 主策略: 用正则表达式匹配 "第一条"/"第1条"/"第一百零八条" 等模式, 按"标题+内容"切分;
# (2) 回退策略: 若文档中没有"第X条"标记(如非标准合同), 则按换行符分段切分, 保证总有输出。
# 每个切分出的条款是一个字典, 包含 id(序号)、title(标题, 如"第一条")、text(完整文本)。
# 该结构便于在最终报告中按条款编号引用风险, 提升可读性与可追溯性。
# 整个过程纯本地计算, 无 LLM 调用, 性能高且零成本。


# 导入 re 模块, 用于正则表达式匹配与切分
# re 是 Python 标准库, 提供 re.split / re.search / re.findall 等函数
import re

# 从同包导入 AgentState 类型, 作为节点函数的类型注解
from __004__langgraph_more_nodes.agent_state import AgentState


def clause_split_node(state: AgentState):
    """
    条款切分节点函数: 按规则将合同全文切分为条款列表, 写入 state["doc_clauses"]。

    作用:
        读取合同全文(state["doc_text"]), 优先按"第X条"正则模式切分为带标题的条款列表;
        若文档无此标记, 则按换行符分段作为回退方案。每个条款以字典形式存储(id/title/text),
        便于后续节点按条款编号定位风险、生成报告。

    参数:
        state (AgentState): LangGraph 共享状态字典。读取字段:
                            - doc_text (str, 可选): 合同全文
                            写入字段:
                            - doc_clauses (List[Dict]): 切分后的条款列表,
                              每个元素形如 {"id": 1, "title": "第一条", "text": "第一条 ..."}

    返回值:
        AgentState: 更新后的状态字典, 必含 "doc_clauses" 字段(可能为空列表)。

    可迁移性说明:
        本节点的"正则切分 + 段落回退"策略可迁移到任何结构化文档切分场景,
        例如: 法规按"第X条"切分、规章制度按章节切分、产品说明书按"1. 2. 3."切分等。
        只需修改正则 pattern 即可适配新的分隔模式。无需 LLM, 性能优异, 推荐保留。
    """
    # 打印节点开始日志
    print("开始条款切分")

    # 从状态字典中取出合同全文, 若不存在则为空字符串
    doc_text = state.get("doc_text", "")

    # 若文档为空(去除空白后), 写入空条款列表并返回, 避免后续无意义处理
    if not doc_text.strip():
        state["doc_clauses"] = []
        return state

    # 主策略: 按 "第X条" 正则模式切分合同
    # 正则解析:
    #   第                    -> 匹配字面量"第"
    #   [一二三四五六七八九十百千零\d]+  -> 匹配中文数字(一到千)或阿拉伯数字(\d), "+" 表示一个或多个
    #   条                    -> 匹配字面量"条"
    #   [、.\s]*              -> 匹配条款后可能跟随的分隔符: 顿号/句号/空白, "*" 表示零个或多个
    # 使用捕获组 (...) 是关键: re.split 在遇到捕获组时, 会把捕获到的分隔符也保留在结果列表中
    # 这样我们就能在切分结果中拿到 "第一条"/"第二条" 等标题
    pattern = r'(第[一二三四五六七八九十百千零\d]+条[、.\s]*)'

    # re.split 用 pattern 切分 doc_text, 返回列表
    # 由于使用了捕获组, 结果格式为: [前文, "第一条", 内容1, "第二条", 内容2, ...]
    # 其中"前文"是第一个"第X条"之前的文本(通常是合同标题/双方信息), 一般不含条款正文
    parts = re.split(pattern, doc_text)

    # clauses 列表用于收集最终的结构化条款
    clauses = []

    # parts 格式说明: [前文, "第一条", 内容1, "第二条", 内容2, ...]
    # 即从索引 1 开始, 奇数索引是标题, 偶数索引是对应内容
    # i 从 1 开始跳过"前文", 每次 +2 跳到下一个标题位置
    i = 1
    while i < len(parts) - 1:
        # 当前索引 i 是条款标题(如"第一条"), 去除首尾空白
        title = parts[i].strip()

        # 下一索引 i+1 是该条款的内容, 去除首尾空白
        # 三元表达式加边界检查: 若 i+1 越界则内容为空字符串(防御性编程)
        content = parts[i + 1].strip() if i + 1 < len(parts) else ""

        # 仅当标题非空时才创建条款(过滤掉空标题)
        if title:
            clauses.append({
                # id 为条款序号, 从 1 开始递增(len(clauses) 在 append 前是当前条数)
                "id": len(clauses) + 1,
                # title 存储条款标题(如"第一条")
                "title": title,
                # text 存储完整条款文本 = 标题 + 空格 + 内容
                # 拼接标题是为了让后续 LLM 审核时能看到完整条款(避免上下文断裂)
                "text": (title + " " + content).strip(),
            })

        # 移动到下一个标题位置(跳过当前的标题和内容)
        i += 2

    # 回退策略: 若主策略未切分出任何条款(文档中没有"第X条"标记), 按段落切分
    # 这处理了非标准合同或自由文本格式的文档
    if not clauses:
        # 按换行符切分文档, 去除空白段落, 保留非空段落
        # 列表推导式: 遍历每行, strip 后非空才保留
        paras = [p.strip() for p in doc_text.split("\n") if p.strip()]

        # 遍历所有段落, 逐个封装为条款字典
        # enumerate(paras, start=0) 返回 (索引, 段落) 对, idx 从 0 开始
        for idx, para in enumerate(paras):
            clauses.append({
                # id 从 1 开始(用户友好, 条款编号通常从1开始)
                "id": idx + 1,
                # title 使用通用命名"条款N"(因为没有"第X条"标记可提取)
                "title": f"条款{idx + 1}",
                # text 直接使用段落内容
                "text": para,
            })

    # 将切分结果写入状态字典
    state["doc_clauses"] = clauses

    # 打印节点完成日志, 显示切分出的条款数量
    print(f"完成条款切分: {len(clauses)} 条")

    # 返回更新后的状态字典
    return state


# 模块自测入口: 直接运行本文件时执行, 验证条款切分逻辑
if __name__ == "__main__":
    # 构造测试状态: 提供一段含"第X条"标记的合同文本
    s = AgentState(doc_text="第一条 甲方购买乙方电脑。第二条 付款方式为现金。")
    # 调用节点, 打印切分出的条款列表
    print(clause_split_node(s).get("doc_clauses"))
